"""
Writes src/ui/logoOutlines.ts: the Gapless wordmark and the G of the mark, as SVG path data
outlined from the site's own Archivo variable font (public/fonts/archivo-latin-var.woff2) at
weight 800, width 75 (the type-display style). Outlines, not live text, so the logo renders
identically in the header, the favicon files, the portrait export and anywhere without the font.

Run after changing the logo's type, and commit the output:
  pip install fonttools brotli uharfbuzz
  python3 scripts/logo-outlines.py
"""
import io
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'public/fonts/archivo-latin-var.woff2'


def instance(wght, wdth):
    f = TTFont(str(FONT))
    f.flavor = None
    f = instantiateVariableFont(f, {'wght': wght, 'wdth': wdth})
    buf = io.BytesIO()
    f.save(buf)
    data = buf.getvalue()
    return TTFont(io.BytesIO(data)), data


def outline(text, size, wght=800, wdth=75, ox=0.0, oy=0.0):
    """Path data for `text` at font size `size`, baseline at (ox, oy). Returns (d, advance, cap)."""
    f, data = instance(wght, wdth)
    upem = f['head'].unitsPerEm
    font = hb.Font(hb.Face(data))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {'kern': True, 'liga': True})
    glyphs = f.getGlyphSet()
    order = f.getGlyphOrder()
    s = size / upem
    x = 0
    parts = []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        pen = SVGPathPen(glyphs, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
        glyphs[order[info.codepoint]].draw(TransformPen(pen, (s, 0, 0, -s, ox + x * s, oy)))
        parts.append(pen.getCommands())
        x += pos.x_advance
    return ' '.join(parts), x * s, f['OS/2'].sCapHeight * s, -f['hhea'].descent * s


# Wordmark: size 100, baseline at y=0. The marker band sits just under the baseline.
word_d, word_w, cap, desc = outline('Gapless', 100)
band_y, band_h = 1.5, 10
top = -cap - 2
bottom = max(band_y + band_h, desc) + 1
# The mark: G at size 24, centred in a 32x32 tile.
g_d0, g_w, g_cap, _ = outline('G', 24)
gx, gy = (32 - g_w) / 2, 16 + g_cap / 2
g_d, _, _, _ = outline('G', 24, ox=gx, oy=gy)

out = f'''// Generated by scripts/logo-outlines.py from public/fonts/archivo-latin-var.woff2 (wght 800,
// wdth 75). Do not edit by hand: change the script and run it again.

/** "Gapless" outlined at font size 100 with its baseline at y = 0. */
export const WORDMARK_PATH = '{word_d}';

/** The wordmark's drawing box: x, y, width, height (a viewBox), including the marker band. */
export const WORDMARK_VIEWBOX = {{ x: -2, y: {top:.2f}, width: {word_w + 4:.2f}, height: {bottom - top:.2f} }} as const;

/** The marker band under the baseline: the highlighter stroke that runs the length of the word. */
export const WORDMARK_BAND = {{ x: -2, y: {band_y}, width: {word_w + 4:.2f}, height: {band_h} }} as const;

/** The G of the mark, already placed in the 0 0 32 32 tile. */
export const MARK_G_PATH = '{g_d}';
'''
(ROOT / 'src/ui/logoOutlines.ts').write_text(out)
print('wrote src/ui/logoOutlines.ts', round(word_w, 2), round(cap, 2))
