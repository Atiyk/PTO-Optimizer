/**
 * Stage 3A glossary data (Feature 1). Worker-side definitions (P1): what a term means and
 * what it implies for the reader, never employer framing. Any legal-sounding claim stays
 * generic ("this varies by where you work") rather than naming a specific jurisdiction's
 * rule without a primary source (P4) - none of these 30 entries cite a specific statute,
 * so `sources` is empty throughout; a future pass that adds jurisdiction-specific rules
 * must add a dated primary source alongside each one, not before.
 *
 * Stage 3D (readability): every `short`/`long` field here is written in short, simple
 * sentences on purpose, not as a style choice - src/content/readability.test.ts fails the
 * build if any field scores above a grade-10 reading level, and the first draft of this
 * file (longer, comma-joined sentences) failed that check almost entirely. Keep sentences
 * short when editing this file; the test will catch anything that drifts.
 */

