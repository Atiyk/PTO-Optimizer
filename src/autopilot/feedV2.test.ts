import { describe, expect, it } from 'vitest';
import { rawHolidaysToHolidays } from '@daysoff/engine/data/holidays';
import fixtures from './__fixtures__/feed-e28eeab.json';
import { holidayFile } from './feedTestHolidays';
import { handleFeedRequest, FEED_CACHE_CONTROL, type HolidayReader } from './feedHandler';
import { buildWatchFeedICS, feedCalendar, pinnedDefaults, policyFromURLState, type WatchFeedHolidays } from './watchFeed';
import { planFromSearch } from './planFromSearch';
import {
  buildPlanFeedV2ICS, buildPlanFeedV2Search, buildWatchFeedV2ICS, buildWatchFeedV2Search, decodeBreakTokens,
  PLAN_FEED_V2_KEYS, WATCH_FEED_V2_KEYS, watchFeedV2Reminders,
} from './feedV2';
import { generateICS } from '../ui/icsExport';
import { readPolicyStateFromURL } from '../ui/policyUrlState';
import { EXPIRATION_REMINDER_LEADS, expirationReminders, expirationRisks } from '../personal/expiration';
import { rescuePlans } from '../personal/expiryRescue';

/** Calendars generated by the e28eeab code (the release before format 2) for format-1
 * links: src/autopilot/__fixtures__/feed-e28eeab.json. Each plan entry is
 * `<status>|<cache-control>|<request time>|<body>`. */
const GOLDEN = fixtures as { commit: string; plan: Record<string, string>; watch: Record<string, string>; download: Record<string, string> };
const reader: HolidayReader = async (country, year) => holidayFile(country, year);
const watchHolidays: WatchFeedHolidays = (country, year) => {
  const raw = holidayFile(country, year);
  return Array.isArray(raw) ? rawHolidaysToHolidays(raw as never) : null;
};

function golden(entry: string) {
  const [status, cache, now, ...rest] = entry.split('|');
  return { status: Number(status), cache, now, body: rest.join('|') };
}
function uids(ics: string): string[] {
  return [...ics.replace(/\r\n /g, '').matchAll(/\r\nUID:([^\r]+)/g)].map((m) => m[1]);
}
function events(ics: string): string[] {
  return ics.replace(/\r\n /g, '').split('BEGIN:VEVENT').slice(1).map((event) => event.split('END:VEVENT')[0]);
}

/** Money, balances and policy values never appear as format-2 keys. */
const POLICY_KEYS = ['b', 'rv', 'w', 'count', 'ac', 'am', 'ex', 'xd', 'cc', 'np', 'nu', 'pc', 'up', 'cb', 'ccb', 'ak', 'hr', 'acp', 'wp', 'nba', 'pd', 'gd', 'bao', 'cub', 'crd', 'pda', 'eh', 'bo', 'od', 'p', 'r'];

describe('format-1 links keep working (compat path, golden from e28eeab)', () => {
  it.each(Object.keys(GOLDEN.plan))('/api/feed?%s returns the same status, cache header and bytes', async (query) => {
    const expected = golden(GOLDEN.plan[query]);
    const res = await handleFeedRequest(new Request(`https://x.test/api/feed?${query}`), reader, new Date(expected.now));
    expect(res.status).toBe(expected.status);
    expect(res.headers.get('cache-control')).toBe(expected.cache);
    expect(await res.text()).toBe(expected.body);
  });

  it.each(Object.keys(GOLDEN.watch))('/api/watch?%s returns the same bytes', (key) => {
    const [query, today] = key.split('@');
    const result = buildWatchFeedICS(query, today, watchHolidays);
    expect(result.ok && result.ics).toBe(GOLDEN.watch[key]);
  });

  it.each(Object.keys(GOLDEN.download))('the per-day .ics download is unchanged for %s (UIDs byte-identical)', (query) => {
    const now = golden(GOLDEN.plan[query]).now;
    const plan = planFromSearch(query, now.slice(0, 10), holidayFile);
    if (!plan.ok) throw new Error(plan.issues.join(' '));
    const ics = generateICS(plan.breaks, plan.isPtoDay, new Date(now), { enabled: true, leadDays: 14, workWeek: plan.state.workWeek, offDays: plan.solveInput.offDays });
    expect(ics).toBe(GOLDEN.download[query]);
    expect(uids(ics)).toEqual(uids(GOLDEN.download[query]));
  });
});

/** The format-2 link the page writes for the plan a format-1 query produces. */
function v2For(query: string, today: string) {
  const plan = planFromSearch(query, today, holidayFile);
  if (!plan.ok) throw new Error(plan.issues.join(' '));
  return buildPlanFeedV2Search({ publicSearch: query, breaks: plan.breaks, isPtoDay: plan.isPtoDay, createdOn: new URLSearchParams(query).get('fc') ?? '' });
}

describe('format-2 plan feed', () => {
  const PARITY = Object.keys(GOLDEN.plan).filter((query) => !query.includes('np='));

  it.each(PARITY)('writes the same calendar as the format-1 link %s, without solving', async (query) => {
    const expected = golden(GOLDEN.plan[query]);
    const today = expected.now.slice(0, 10);
    const v2 = v2For(query, today);
    const result = buildPlanFeedV2ICS(v2, today, holidayFile);
    if (!result.ok) throw new Error(result.message);
    expect(result.ics).toBe(expected.body);
    const res = await handleFeedRequest(new Request(`https://x.test/api/feed?${v2}`), reader, new Date(expected.now));
    expect(res.status).toBe(200);
    expect(await res.text()).toBe(expected.body);
    expect(res.headers.get('cache-control')).toBe(query.includes('ho=') ? 'private, no-store' : FEED_CACHE_CONTROL);
  });

  it('keeps the PTO-day UIDs of a plan whose old link carried private settings', () => {
    const query = Object.keys(GOLDEN.plan).find((key) => key.includes('np='))!;
    const expected = golden(GOLDEN.plan[query]);
    const result = buildPlanFeedV2ICS(v2For(query, expected.now.slice(0, 10)), expected.now.slice(0, 10), holidayFile);
    if (!result.ok) throw new Error(result.message);
    const pto = (ics: string) => uids(ics).filter((uid) => /^pto-\d{8}@/.test(uid));
    expect(pto(result.ics)).toEqual(pto(expected.body));
    expect(pto(result.ics).length).toBeGreaterThan(0);
  });

  it.each(Object.keys(GOLDEN.plan))('carries no balance, accrual, expiry, carryover or notice values (%s)', (query) => {
    const v2 = new URLSearchParams(v2For(query, golden(GOLDEN.plan[query]).now.slice(0, 10)));
    for (const key of v2.keys()) expect(PLAN_FEED_V2_KEYS as readonly string[]).toContain(key);
    for (const key of POLICY_KEYS) expect(v2.has(key)).toBe(false);
    // Every value is a code, a date, a 0/1 work week or the break tokens (dates + 0/1 masks).
    for (const [key, value] of v2) {
      if (key === 'k') expect(value).toMatch(/^(\d{8}-\d{8}-[01]+(-\d+(\.\d+)?)?)(_\d{8}-\d{8}-[01]+(-\d+(\.\d+)?)?)*$/);
      else if (key === 'ho') expect(value).toMatch(/^(\d{4}-\d{2}-\d{2})?(,\d{4}-\d{2}-\d{2})*$/);
      else expect(value).toMatch(/^([A-Z]{2}(-[A-Z0-9]+)?|\d{4}-\d{2}-\d{2}|[01]{7}|[12])$/);
    }
  });

  it('rejects malformed or oversized break tokens with 400', async () => {
    for (const k of ['2027010-20270105-1', '20270101-20270105-11', '20270105-20270101-1', `20270101-20270601-${'1'.repeat(152)}`, '20270101-20270102-11_20270102-20270103-11']) {
      expect(decodeBreakTokens(k)).toBeNull();
      const res = await handleFeedRequest(new Request(`https://x.test/api/feed?fv=2&c=US&s=2027-01-01&e=2027-12-31&k=${k}`), reader, new Date('2026-11-14T00:00:00Z'));
      expect(res.status).toBe(400);
      expect(res.headers.get('cache-control')).toBe('no-store');
    }
  });

  it('a range longer than three years is refused before any holiday is read', async () => {
    let reads = 0;
    const res = await handleFeedRequest(new Request('https://x.test/api/feed?fv=2&c=US&s=2027-01-01&e=2031-01-01&k='), async () => { reads += 1; return null; }, new Date('2026-11-14T00:00:00Z'));
    expect([400, 422]).toContain(res.status);
    expect(reads).toBeLessThanOrEqual(5);
  });
});

/** The risks and rescue plans a format-1 watch link computes for `today`, as the page does. */
function watchInputs(search: string, today: string) {
  const state = readPolicyStateFromURL(pinnedDefaults(search, today), 'US');
  const policy = policyFromURLState(state);
  const risks = expirationRisks(policy, 'US', [], today);
  const horizon = risks.reduce((latest, risk) => (risk.deadline > latest ? risk.deadline : latest), today);
  const { calendar } = feedCalendar(state, today, horizon, watchHolidays);
  const plans = rescuePlans(risks, { policy, country: 'US', requests: [], calendar, today });
  return buildWatchFeedV2Search(
    watchFeedV2Reminders(expirationReminders(risks, EXPIRATION_REMINDER_LEADS, today), risks),
    [...plans.values()].map((plan) => ({ riskId: plan.riskId, deadline: plan.deadline, dates: plan.ptoDates.filter((date) => date >= today) })),
    today,
  );
}

describe('format-2 expiry watch feed', () => {
  it.each(Object.keys(GOLDEN.watch))('has the same event UIDs and dates as the format-1 feed (%s)', (key) => {
    const [query, today] = key.split('@');
    const v2 = watchInputs(query, today);
    const result = buildWatchFeedV2ICS(v2, today);
    if (!result.ok) throw new Error(result.message);
    const shape = (ics: string) => events(ics).map((event) => `${/UID:([^\r]+)/.exec(event)![1]} ${/DTSTART;VALUE=DATE:(\d+)/.exec(event)![1]} ${event.includes('VALARM')}`).sort();
    expect(shape(result.ics)).toEqual(shape(GOLDEN.watch[key]));
  });

  it('carries no balance or policy values, and the calendar names no day counts', () => {
    const v2 = watchInputs('ak=fl&am=0&gd=2026-01-01&cc=5&cb=8&bao=2026-10-01&c=US', '2026-10-01');
    const params = new URLSearchParams(v2);
    for (const key of params.keys()) expect(WATCH_FEED_V2_KEYS as readonly string[]).toContain(key);
    for (const key of POLICY_KEYS.filter((key) => key !== 'r')) expect(params.has(key)).toBe(false);
    expect(params.get('r')).toMatch(/^[fca]\d{8}-\d{1,3}\.\d{8}\.\d{8}(_[fca]\d{8}-\d{1,3}\.\d{8}\.\d{8})*$/);
    const result = buildWatchFeedV2ICS(v2, '2026-10-01');
    if (!result.ok) throw new Error(result.message);
    const text = result.ics.replace(/\r\n /g, '');
    expect(text).not.toMatch(/lose \d|\d+(\.\d+)? (PTO )?days? (at risk|expire)|keeps? \d/);
    expect(text).toContain('does not hold your balance and is not recalculated');
    for (const line of result.ics.split('\r\n')) expect(new TextEncoder().encode(line).length).toBeLessThanOrEqual(75);
  });

  it('drops past dates at fetch time and refuses malformed items', async () => {
    const v2 = watchInputs('ak=fl&am=0&gd=2026-01-01&cc=5&cb=8&bao=2026-10-01&c=US', '2026-10-01');
    const later = buildWatchFeedV2ICS(v2, '2026-12-29');
    if (!later.ok) throw new Error(later.message);
    expect(events(later.ics).every((event) => /DTSTART;VALUE=DATE:(\d+)/.exec(event)![1] >= '20261229')).toBe(true);
    expect(buildWatchFeedV2ICS('wv=2&r=zz', '2026-10-01').ok).toBe(false);
  });

});
